// Embeds a TTF as a base64 module so every host (RN, browser) loads it the same way, with no asset pipeline.
import { readFileSync, writeFileSync } from 'node:fs';

const [src, out, name] = process.argv.slice(2);
const b64 = readFileSync(src).toString('base64');
writeFileSync(
  out,
  `// Generated by scripts/embed-font.mjs from ${src.split('/').pop()} (SIL Open Font License).\n` +
    `export const FONT_NAME = '${name}';\nexport const FONT_BASE64 =\n  '${b64}';\n`
);
